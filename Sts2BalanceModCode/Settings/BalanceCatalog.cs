  internal static void Migrate(Dictionary<string, bool> choices, bool leave, bool prism, bool doll)
  {
    foreach (BalanceChange c in All)
      choices.TryAdd(c.Id, c.Id switch
      {
        "E02" or "E15" or "E16" => leave,
        "M02" => prism,
        "E14" => doll,
        _ => true
      });
  }

  internal static bool Pending(IReadOnlyDictionary<string, bool> selected, IReadOnlyDictionary<string, bool> active, string id) =>
    selected.GetValueOrDefault(id, true) != active.GetValueOrDefault(id, true) || Effective(selected, id) != Effective(active, id);

  public static bool Effective(IReadOnlyDictionary<string, bool> values, string id) =>
    (!values.TryGetValue(id, out bool value) || value) &&
    (id != "R04" || Effective(values, "E06") || Effective(values, "E11"));
}
